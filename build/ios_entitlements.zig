//! Entitlements embedded in iOS simulator executables, as Xcode does: the
//! simulator can't carry restricted entitlements in the code signature
//! (SpringBoard refuses to launch such an app), so they live in the
//! `__TEXT,__entitlements` (XML plist) and `__TEXT,__ents_der` (DER)
//! sections, where the simulator's Security framework reads them. Daemons
//! that identify the client by its `application-identifier` (nsurlsessiond
//! for background URLSessions, the keychain) need them.

const std = @import("std");

pub const Entitlements = struct {
    /// `<team id>.<bundle id>`, or `.<bundle id>` without a team.
    application_identifier: []const u8,
};

/// `<team>.<bundle id>`; an empty or null team leaves the leading dot.
pub fn applicationIdentifier(gpa: std.mem.Allocator, team_id: ?[]const u8, bundle_id: []const u8) ![]u8 {
    return std.fmt.allocPrint(gpa, "{s}.{s}", .{ team_id orelse "", bundle_id });
}

/// The XML plist (the `.xcent` file Xcode writes).
pub fn xml(gpa: std.mem.Allocator, e: Entitlements) ![]u8 {
    return std.fmt.allocPrint(gpa,
        \\<?xml version="1.0" encoding="UTF-8"?>
        \\<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        \\<plist version="1.0">
        \\<dict>
        \\    <key>application-identifier</key>
        \\    <string>{s}</string>
        \\    <key>com.apple.security.get-task-allow</key>
        \\    <true/>
        \\    <key>keychain-access-groups</key>
        \\    <array>
        \\        <string>{s}</string>
        \\    </array>
        \\</dict>
        \\</plist>
        \\
    , .{ e.application_identifier, e.application_identifier });
}

/// The DER form (`codesign --generate-entitlement-der`): [APPLICATION 16]
/// { INTEGER 1, [CONTEXT 16] { SEQUENCE { UTF8String key, value } ... } },
/// the keys in sorted order.
pub fn der(gpa: std.mem.Allocator, e: Entitlements) ![]u8 {
    var dict: std.ArrayList(u8) = .empty;
    defer dict.deinit(gpa);
    // Keys sorted: application-identifier < com.apple... < keychain-access-groups.
    try entry(gpa, &dict, "application-identifier", .{ .string = e.application_identifier });
    try entry(gpa, &dict, "com.apple.security.get-task-allow", .{ .boolean = true });
    try entry(gpa, &dict, "keychain-access-groups", .{ .string_array = e.application_identifier });

    var body: std.ArrayList(u8) = .empty;
    defer body.deinit(gpa);
    try body.appendSlice(gpa, &.{ 0x02, 0x01, 0x01 }); // INTEGER 1
    try tlv(gpa, &body, 0xB0, dict.items); // [CONTEXT 16] constructed: the dictionary

    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try tlv(gpa, &out, 0x70, body.items); // [APPLICATION 16] constructed
    return out.toOwnedSlice(gpa);
}

const Value = union(enum) { string: []const u8, boolean: bool, string_array: []const u8 };

fn entry(gpa: std.mem.Allocator, out: *std.ArrayList(u8), key: []const u8, value: Value) !void {
    var seq: std.ArrayList(u8) = .empty;
    defer seq.deinit(gpa);
    try tlv(gpa, &seq, 0x0C, key);
    switch (value) {
        .string => |s| try tlv(gpa, &seq, 0x0C, s),
        .boolean => |v| try seq.appendSlice(gpa, &.{ 0x01, 0x01, if (v) 0xFF else 0x00 }),
        .string_array => |s| {
            var arr: std.ArrayList(u8) = .empty;
            defer arr.deinit(gpa);
            try tlv(gpa, &arr, 0x0C, s);
            try tlv(gpa, &seq, 0x30, arr.items);
        },
    }
    try tlv(gpa, out, 0x30, seq.items);
}

/// Tag, DER definite length, contents (lengths up to 64 KiB: plenty).
fn tlv(gpa: std.mem.Allocator, out: *std.ArrayList(u8), tag: u8, contents: []const u8) !void {
    try out.append(gpa, tag);
    const n = contents.len;
    if (n < 0x80) {
        try out.append(gpa, @intCast(n));
    } else if (n <= 0xFF) {
        try out.appendSlice(gpa, &.{ 0x81, @intCast(n) });
    } else if (n <= 0xFFFF) {
        try out.appendSlice(gpa, &.{ 0x82, @intCast(n >> 8), @intCast(n & 0xFF) });
    } else return error.TooLong;
    try out.appendSlice(gpa, contents);
}

/// A C file placing both forms in their sections (no trailing NUL, like
/// Xcode's `-sectcreate` of the files).
pub fn cSource(gpa: std.mem.Allocator, e: Entitlements) ![]u8 {
    const x = try xml(gpa, e);
    defer gpa.free(x);
    const d = try der(gpa, e);
    defer gpa.free(d);
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa, "// Generated by Oriel (build/ios_entitlements.zig): simulator entitlements.\n");
    try array(gpa, &out, "__entitlements", "oriel_entitlements_xml", x);
    try array(gpa, &out, "__ents_der", "oriel_entitlements_der", d);
    return out.toOwnedSlice(gpa);
}

fn array(gpa: std.mem.Allocator, out: *std.ArrayList(u8), section: []const u8, name: []const u8, bytes: []const u8) !void {
    try out.print(gpa, "__attribute__((used, section(\"__TEXT,{s}\"))) static const unsigned char {s}[{d}] = {{", .{ section, name, bytes.len });
    for (bytes, 0..) |byte, i| try out.print(gpa, "{s}0x{x:0>2}", .{ if (i == 0) "" else ",", byte });
    try out.appendSlice(gpa, "};\n");
}

test applicationIdentifier {
    const gpa = std.testing.allocator;
    const with = try applicationIdentifier(gpa, "ABCDE12345", "dev.app.x");
    defer gpa.free(with);
    try std.testing.expectEqualStrings("ABCDE12345.dev.app.x", with);
    const without = try applicationIdentifier(gpa, null, "dev.app.x");
    defer gpa.free(without);
    try std.testing.expectEqualStrings(".dev.app.x", without);
}

test der {
    const gpa = std.testing.allocator;
    const d = try der(gpa, .{ .application_identifier = "T.a" });
    defer gpa.free(d);
    const want = "\x70\x6d" ++ "\x02\x01\x01" ++ "\xb0\x68" ++
        "\x30\x1d" ++ "\x0c\x16application-identifier" ++ "\x0c\x03T.a" ++
        "\x30\x26" ++ "\x0c\x21com.apple.security.get-task-allow" ++ "\x01\x01\xff" ++
        "\x30\x1f" ++ "\x0c\x16keychain-access-groups" ++ "\x30\x05\x0c\x03T.a";
    try std.testing.expectEqualSlices(u8, want, d);
}

test cSource {
    const gpa = std.testing.allocator;
    const c = try cSource(gpa, .{ .application_identifier = ".dev.app.x" });
    defer gpa.free(c);
    try std.testing.expect(std.mem.indexOf(u8, c, "section(\"__TEXT,__entitlements\")") != null);
    try std.testing.expect(std.mem.indexOf(u8, c, "section(\"__TEXT,__ents_der\")") != null);
}
