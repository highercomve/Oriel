// Bundles src/main.js (with linkedom) into ../runtime.js, the script the Zig
// side embeds and runs in QuickJS. Run `npm install && npm run build` after
// changing src/.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { readFile } from "node:fs/promises";

// QuickJS has no atob (HTML entity tables are base64).
const atob = `globalThis.atob ??= (s) => {
  const abc = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  let out = "", buf = 0, bits = 0;
  for (const ch of String(s).replace(/[^A-Za-z0-9+/]/g, "")) {
    buf = (buf << 6) | abc.indexOf(ch); bits += 6;
    if (bits >= 8) { bits -= 8; out += String.fromCharCode((buf >> bits) & 255); }
  }
  return out;
};`;
const shim = fileURLToPath(new URL("node_modules/linkedom/commonjs/canvas-shim.cjs", import.meta.url));
await build({
  entryPoints: ["src/main.js"],
  bundle: true,
  format: "iife",
  target: "es2023",
  platform: "neutral",
  mainFields: ["module", "main"],
  outfile: "../runtime.js",
  legalComments: "inline",
  banner: { js: "// Generated by src/native_ui/js/build.mjs from src/native_ui/js/src: edit those, then `npm run build`.\n" + atob },
  plugins: [{
    name: "connected-renderer-observer",
    setup(b) {
      b.onLoad({ filter: /linkedom[/\\]esm[/\\]interface[/\\]mutation-observer\.js$/ }, async ({ path }) => {
        const source = await readFile(path, "utf8");
        const split = source.indexOf("export const moCallback =");
        const marker = "        if (childList) {";
        if (split < 0 || !source.slice(0, split).includes(marker) || !source.slice(split).includes(marker)) {
          throw new Error("Review the renderer observer patch for this linkedom version");
        }
        // linkedom's document observer sees detached construction too.
        // The renderer needs only the final insertion into the document:
        // don't allocate records for every detached attribute/append.
        // Page-created observers retain linkedom's original behavior.
        const attributes = source.slice(0, split).replace(marker,
          "        if (observer.__nuiConnectedOnly && target === ownerDocument) {\n" +
          "          if (!element.isConnected) continue;\n" +
          "          if (observer.__nuiAttribute) { observer.__nuiAttribute(element, attributeName); break; }\n" +
          "        }\n" + marker);
        const children = source.slice(split).replace(marker,
          "        if (observer.__nuiConnectedOnly && target === ownerDocument) {\n" +
          "          if (!(parentNode || element).isConnected) continue;\n" +
          "          if (observer.__nuiChild) { observer.__nuiChild(element, parentNode); break; }\n" +
          "        }\n" + marker);
        return { contents: attributes + children, loader: "js" };
      });
    },
  }, {
    name: "no-canvas",
    // linkedom tries the `canvas` package for <canvas>; its shim is enough here.
    setup(b) { b.onResolve({ filter: /canvas\.cjs$/ }, () => ({ path: shim })); },
  }],
  logLevel: "warning",
});
